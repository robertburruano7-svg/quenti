/**
 * Builds the text of the macOS `.app` bundle: the launcher script and the
 * Info.plist.
 *
 * Pure string functions, kept separate from `make-app.ts` so they can be tested
 * without a Mac. Nothing here touches the filesystem or shells out.
 *
 * The launcher is shell because a `.app` executable has to be. It is generated
 * rather than committed so the repo path can be baked in: an app launched from
 * Finder starts in `/`, not the project directory.
 */

